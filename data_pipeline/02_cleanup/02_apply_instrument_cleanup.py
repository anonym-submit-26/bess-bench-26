#!/usr/bin/env python3
"""
Apply instrument standardization to DuckDB.

Reads instrument_lookup.json (generated by 01_analyze_instruments.py)
and adds/updates 5 columns in spectra_votable:
  - telescope_clean    (e.g. C11, RC400, OHP_T193)
  - spectrograph_clean (e.g. eShel, LhiresIII, MUSICOS)
  - detector_clean     (e.g. Atik460, ASI2600, QSI532)
  - instrument_setup   (e.g. C11+eShel+Atik460)
  - instrument_confidence (high / medium / low)
"""

import json
import duckdb
from pathlib import Path


def main():
    db_path = Path(__file__).parent.parent.parent / 'harvest' / 'bess_data.duckdb'
    lookup_path = Path(__file__).parent / 'instrument_lookup.json'
    
    # Load the lookup
    print(f"Loading {lookup_path}")
    with open(lookup_path, 'r', encoding='utf-8') as f:
        lookup = json.load(f)
    
    print(f"  {len(lookup)} entries in the lookup")
    
    conn = duckdb.connect(str(db_path))
    
    # --- Check existing columns ---
    existing = {row[0] for row in conn.execute("DESCRIBE spectra_votable").fetchall()}
    
    new_columns = {
        'telescope_clean': 'VARCHAR',
        'spectrograph_clean': 'VARCHAR',
        'detector_clean': 'VARCHAR',
        'instrument_setup': 'VARCHAR',
        'instrument_confidence': 'VARCHAR',
    }
    
    for col, dtype in new_columns.items():
        if col not in existing:
            print(f"  Adding column: {col} ({dtype})")
            conn.execute(f"ALTER TABLE spectra_votable ADD COLUMN {col} {dtype}")
        else:
            print(f"  Existing column: {col} — reset to NULL")
            conn.execute(f"UPDATE spectra_votable SET {col} = NULL")
    
    # --- Apply the lookup via a temporary table ---
    # Create a temporary table with the mapping
    conn.execute("DROP TABLE IF EXISTS _instrument_lookup")
    conn.execute("""
        CREATE TEMPORARY TABLE _instrument_lookup (
            fits_bss_inst VARCHAR,
            telescope_clean VARCHAR,
            spectrograph_clean VARCHAR,
            detector_clean VARCHAR,
            instrument_setup VARCHAR,
            instrument_confidence VARCHAR
        )
    """)
    
    # Insert lookup data
    rows = []
    for raw, info in lookup.items():
        rows.append((
            raw,
            info.get('telescope'),
            info.get('spectrograph'),
            info.get('detector'),
            info.get('instrument_setup'),
            info.get('confidence'),
        ))
    
    conn.executemany(
        "INSERT INTO _instrument_lookup VALUES (?, ?, ?, ?, ?, ?)",
        rows
    )
    print(f"\n  Temporary table: {len(rows)} entries inserted")
    
    # --- UPDATE via JOIN ---
    print("\n  Applying the mapping...")
    result = conn.execute("""
        UPDATE spectra_votable AS s
        SET 
            telescope_clean = l.telescope_clean,
            spectrograph_clean = l.spectrograph_clean,
            detector_clean = l.detector_clean,
            instrument_setup = l.instrument_setup,
            instrument_confidence = l.instrument_confidence
        FROM _instrument_lookup AS l
        WHERE s.fits_bss_inst = l.fits_bss_inst
    """)
    
    # Check number of affected rows
    updated = conn.execute("""
        SELECT COUNT(*) FROM spectra_votable 
        WHERE instrument_confidence IS NOT NULL
    """).fetchone()[0]
    
    total = conn.execute("SELECT COUNT(*) FROM spectra_votable").fetchone()[0]
    
    null_inst = conn.execute("""
        SELECT COUNT(*) FROM spectra_votable 
        WHERE fits_bss_inst IS NULL
    """).fetchone()[0]
    
    print(f"  Rows updated: {updated:,} / {total:,}")
    print(f"  Rows without fits_bss_inst: {null_inst:,}")
    print(f"  Rows not mapped: {total - updated - null_inst:,}")
    
    # --- Validation statistics ---
    print("\n" + "=" * 60)
    print("VALIDATION")
    print("=" * 60)
    
    # Confidence
    confidence_stats = conn.execute("""
        SELECT instrument_confidence, COUNT(*) as cnt
        FROM spectra_votable
        WHERE instrument_confidence IS NOT NULL
        GROUP BY instrument_confidence
        ORDER BY cnt DESC
    """).fetchall()
    
    print(f"\n--- Confidence distribution ---")
    for level, cnt in confidence_stats:
        print(f"  {level:<8}: {cnt:>8,} spectra ({cnt/total*100:.1f}%)")
    
    # Coverage by component
    for col in ('telescope_clean', 'spectrograph_clean', 'detector_clean'):
        filled = conn.execute(f"""
            SELECT COUNT(*) FROM spectra_votable WHERE {col} IS NOT NULL
        """).fetchone()[0]
        unique = conn.execute(f"""
            SELECT COUNT(DISTINCT {col}) FROM spectra_votable WHERE {col} IS NOT NULL
        """).fetchone()[0]
        print(f"\n  {col}:")
        print(f"    Non-NULL: {filled:,} ({filled/total*100:.1f}%)")
        print(f"    Unique values: {unique}")
    
    # Top 15 setups
    top_setups = conn.execute("""
        SELECT instrument_setup, COUNT(*) as cnt
        FROM spectra_votable
        WHERE instrument_setup IS NOT NULL
        GROUP BY instrument_setup
        ORDER BY cnt DESC
        LIMIT 15
    """).fetchall()
    
    print(f"\n--- Top 15 instrument_setup ---")
    for setup, cnt in top_setups:
        print(f"  {cnt:>8,} | {setup}")
    
    # Cleanup
    conn.execute("DROP TABLE IF EXISTS _instrument_lookup")
    conn.close()
    
    print(f"\n✓ Standardization complete. {updated:,} spectra updated.")


if __name__ == '__main__':
    main()
